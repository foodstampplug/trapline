<script lang="ts">
  // Deck launcher — the 📡 rail panel that starts/stops the trapline-deck
  // phone-remote (a local Node process + optional cloudflared tunnel) so the
  // user can drive Trapline from their phone, already logged in, over Wi-Fi.
  // Ported from main:index.html #deck + main:src/main.js renderDeck()/
  // deckStart()/deckStop()/deckSaveFolder()/deckDot()/copyText() (~lines
  // 706-772). Same modal-card shell as FindingsPanel.svelte/Loot.svelte/
  // Settings.svelte.
  import { deckStart, deckStop, deckStatus, deckSetFolder } from '$lib/bridge';
  import type { DeckStatus } from '$lib/types';

  let { open = $bindable(false) }: { open?: boolean } = $props();

  type DotState = 'stopped' | 'starting' | 'running';

  let status = $state<DeckStatus>({ running: false });
  let dotState = $state<DotState>('stopped');
  let folder = $state('');
  let starting = $state(false);
  let folderSaved = $state(false);
  let folderSavedTimer: ReturnType<typeof setTimeout> | undefined;
  let copied = $state<string | null>(null);
  let copiedTimer: ReturnType<typeof setTimeout> | undefined;

  const tunnelCmd = $derived(status.port ? `cloudflared tunnel --url http://localhost:${status.port}` : '');

  // Load current state whenever the panel OPENS — not on unconditional
  // mount. <Deck> is mounted once for the whole session (like Loot/
  // Settings/FindingsPanel) inside Cockpit.svelte; if this fired
  // unconditionally it would hit the Tauri bridge as soon as Cockpit
  // mounts, which throws outside a real Tauri webview and breaks
  // Cockpit.test.ts. Gating on `open` keeps the closed instance inert.
  $effect(() => {
    if (!open) return;
    void refresh();
  });

  async function refresh(): Promise<void> {
    try {
      const s = await deckStatus();
      applyStatus(s);
    } catch (e) {
      console.error(e);
    }
  }

  function applyStatus(s: DeckStatus): void {
    status = s;
    dotState = s.running ? 'running' : 'stopped';
  }

  function close(): void {
    open = false;
  }

  async function start(): Promise<void> {
    dotState = 'starting';
    starting = true;
    try {
      const s = await deckStart();
      applyStatus(s);
    } catch (e) {
      console.error(e);
      dotState = 'stopped';
    } finally {
      starting = false;
    }
  }

  async function stop(): Promise<void> {
    try {
      await deckStop();
      applyStatus({ running: false });
    } catch (e) {
      console.error(e);
      // Stop failed — resync to the real state instead of leaving the UI stale.
      await refresh();
    }
  }

  async function saveFolder(): Promise<void> {
    try {
      await deckSetFolder(folder.trim());
      folderSaved = true;
      clearTimeout(folderSavedTimer);
      folderSavedTimer = setTimeout(() => (folderSaved = false), 1500);
    } catch (e) {
      console.error(e);
    }
  }

  async function copy(text: string, label: string): Promise<void> {
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      copied = label;
      clearTimeout(copiedTimer);
      copiedTimer = setTimeout(() => (copied = null), 1500);
    } catch (e) {
      console.error(e);
    }
  }

  function onWindowKeydown(e: KeyboardEvent): void {
    if (open && e.key === 'Escape') {
      e.preventDefault();
      close();
    }
  }
</script>

<svelte:window onkeydown={onWindowKeydown} />

{#if open}
  <div class="overlay">
    <button type="button" class="backdrop" aria-label="Close deck" onclick={close}></button>
    <div class="modal-card" role="dialog" aria-modal="true" aria-label="Deck">
      <div class="modal-head">
        <h2>
          📡 Deck
          <span class="dot {dotState}"></span>
