        </h2>
        <button type="button" class="icon-btn sm" title="Close" onclick={close}>✕</button>
      </div>
      <p class="modal-sub">
        Run the phone remote on this machine, then scan the QR to open it on your phone — already
        logged in — over your Wi-Fi.
      </p>

      <div class="deck-controls">
        {#if !status.running}
          <button type="button" class="run-btn" onclick={start} disabled={starting}>
            {starting ? 'Starting…' : 'Start Deck ▸'}
          </button>
        {:else}
          <button type="button" class="ghost-btn" onclick={stop}>Stop</button>
          {#if status.url}
            <a class="ghost-btn" href={status.url} target="_blank" rel="noreferrer">Open on this PC</a>
          {/if}
        {/if}
      </div>

      {#if status.running}
        <div class="deck-running">
          <div class="deck-qr">
            {#if status.lanUrl && status.qrSvg}
              <!-- qrSvg is trusted, generated by our Rust qrcode crate -->
              {@html status.qrSvg}
            {:else}
              <p class="qr-fallback">Couldn't detect a LAN IP — use the tunnel command below.</p>
            {/if}
          </div>

          {#if status.lanUrl}
            <div class="deck-row">
              <label for="deckLanUrl">On this Wi-Fi</label>
              <div class="deck-copy">
                <code id="deckLanUrl">{status.lanUrl}</code>
                <button type="button" class="ghost-btn sm" onclick={() => copy(status.lanUrl ?? '', 'lan')}>
                  {copied === 'lan' ? 'Copied ✓' : 'Copy'}
                </button>
              </div>
            </div>
          {/if}

          <div class="deck-row">
            <label for="deckToken">Token</label>
            <div class="deck-copy">
              <code id="deckToken">{status.token ?? ''}</code>
              <button type="button" class="ghost-btn sm" onclick={() => copy(status.token ?? '', 'token')}>
                {copied === 'token' ? 'Copied ✓' : 'Copy'}
              </button>
            </div>
          </div>

          <div class="deck-row">
            <label for="deckTunnelCmd">Off your network? Run a tunnel, then open the printed URL</label>
            <div class="deck-copy">
              <code id="deckTunnelCmd">{tunnelCmd}</code>
              <button type="button" class="ghost-btn sm" onclick={() => copy(tunnelCmd, 'tunnel')}>
                {copied === 'tunnel' ? 'Copied ✓' : 'Copy'}
              </button>
            </div>
          </div>

          <p class="deck-note">
            Same Wi-Fi? Just scan the QR. First phone connection may need Windows Firewall to allow
            <b>node.exe</b> (one-time).
          </p>
        </div>
      {/if}

      <details class="deck-adv">
        <summary>Advanced — Deck folder</summary>
        <label for="deckFolder">Path to your trapline-deck folder</label>
        <div class="deck-copy">
          <input
            id="deckFolder"
            type="text"
            spellcheck="false"
            placeholder="C:\Users\you\trapline-deck"
            bind:value={folder}
          />
          <button type="button" class="ghost-btn sm" onclick={saveFolder}>
            {folderSaved ? 'Saved ✓' : 'Save'}
          </button>
        </div>
      </details>

      <div class="modal-actions">
        <span class="spacer"></span>
        <button type="button" class="ghost-btn" onclick={close}>Close</button>
      </div>
    </div>
  </div>
{/if}

